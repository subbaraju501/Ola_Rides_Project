-- 1. Total Revenue From SuccessFul Rides

select sum(TotalFareINR) from ola_ride
where BookingStatus = "Completed";

-- 2. Revenue By Vehicle wise

select VehicleType,sum(TotalFareINR) as TotalRevenue
from ola_ride
group by VehicleType
order by TotalRevenue desc;

-- 3. Total Number Of Bookings

select count(*) as Total_Completed_Rides
from ola_ride
where BookingStatus = "Completed";

-- 4. How many Bookings cancle

select count(*) as CancleBookings from ola_ride
where BookingStatus like "Cancelled%";

-- 5. How many Rides Cancle by customer or System or Driver

select CanclledBY,count(*) Rides from ola_ride
where BookingStatus like "Cancelled%" or BookingStatus like "No%"
group by CanclledBY ;

-- 6. Percentage of Bookings Canclled

select CanclledBY,count(*)* 100/
(select count(*) from ola_ride) as CancledRidesPercent
from ola_ride
where BookingStatus like "Cancelled%" or BookingStatus like "No%"
group by CanclledBY ;

-- 7. Percentage of Bookings Compeleted

select count(*)*100/
(select count(*) from ola_ride) as CompletedPercent
from ola_ride
where BookingStatus = "Completed";

-- 8. Avg Booking Value 
select Avg(TotalFareINR) from ola_ride;

-- 9. Avg Ride distance
select avg(RideDistance) from ola_ride;

-- 10. Avg customer Rating
select avg(CustomerRating) from ola_ride;

-- 11. Revenue generated By day
select dayname(BookingDate) as Dayname,sum(TotalFareINR) Revenue
from ola_ride
group by weekday(BookingDate),dayname(BookingDate)
order by weekday(BookingDate);

-- 12. Revenue Generated By month
select monthname(BookingDate) Month_name,Sum(TotalFareINR) Revenue
from ola_ride
group by monthname(BookingDate),month(BookingDate)
order by month(BookingDate);

-- 13. Which Vehicle type Generates Highest Revenue
select VehicleType,Sum(TotalFareINR) as Revenue
from ola_ride
group by VehicleType
order by Revenue desc
limit 1;

-- 14. Highest Revenue Generated By Payment Method
select PaymentMethod,Sum(TotalFareINR) as Revenue
from ola_ride
group by PaymentMethod
order by Revenue desc
limit 1;

-- 15. Avg Revenue By Paymentmethod
select PaymentMethod,Avg(TotalFareINR) Total from ola_ride 
where PaymentMethod is Not null and trim(PaymentMethod)<>''
group by PaymentMethod;

-- 16. Avg Booking value By Vehicle type
select VehicleType,avg(TotalFareINR) from ola_ride
group by VehicleType;

-- 17. Which day of had highest ride demand
select dayname(BookingDate) DayName ,count(RideID) Rides
from ola_ride
group by weekday(BookingDate),dayname(BookingDate)
order by Rides desc
limit 1;

-- 18. what perecent of total revenue comes from each vehicletype
select VehicleType, sum(TotalFareINR)*100/
(select sum(TotalFareINR) from ola_ride
) as Percentage
from ola_ride
group by VehicleType;

-- 19. which hour of the day has highest number of Bookings
select hour(BookingTime),count(RideID) TotalRides from ola_ride
group by hour(BookingTime)
order by  TotalRides desc
limit 1;

-- 20. Unique Customers and total Rides
select CustomerID ,count(distinct(RideID))  total from ola_ride
where CustomerID = "C8"
group by CustomerID;

-- 21. Customer Booked Most Rides
select CustomerID,count(RideID) Total from ola_ride
group by CustomerID
order by Total desc
limit 1;
-- Min
select CustomerID,RideDistance,RideID,BookingDate,BookingTime,VehicleType,BookingStatus,City, count(RideID) total  from ola_ride
group by CustomerID,RideDistance,RideID,BookingDate,BookingTime,VehicleType,BookingStatus,City
order by total asc
limit 1;


-- 22. Revenue Generated By Customer
select CustomerID,sum(TotalFareINR) Total from ola_ride
group by CustomerID
order by Total desc
limit 1;

-- City wise Revenue
select City,sum(TotalFareINR),count(RideID) from ola_ride
group by City;

-- 23. Cancle rate by Vehicle type
select VehicleType, round(100*
sum(BookingStatus like "Cancelled%" or BookingStatus like "No%")/count(BookingStatus),
2) as CancleRate 
from ola_ride
group by VehicleType
order by CancleRate desc;

